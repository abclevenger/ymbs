// ─── Helpers ───
function normalize(pathname: string): string {
  return pathname.replace(/\/+$/, "") || "/";
}

function resolveRedirect(pathname: string): string | null {
  const normalized = normalize(pathname);
  const lower = normalized.toLowerCase();

  if (legacyRedirects[lower]) return legacyRedirects[lower];

  // /blog/:slug → /insights/:slug
  if (lower === "/blog") return "/insights";
  if (lower.startsWith("/blog/")) {
    const slug = normalized.replace("/blog/", "");
    return `/insights/${slug}`;
  }

  // Homepage aliases
  if (homepageAliases.includes(lower)) return "/";

  return null;
}

function isValidRoute(pathname: string): boolean {
  const normalized = normalize(pathname);
  if (validPageRoutes.includes(normalized)) return true;
  if (noIndexRoutes.includes(normalized)) return true;
  return dynamicRoutePrefixes.some((p) => normalized.startsWith(p));
}

// ─── Cloudflare Pages Function ───
interface Env {
  ASSETS: { fetch: (request: Request) => Promise<Response> };
}

export const onRequest: PagesFunction<Env> = async (context) => {
  const { request, env } = context;
  const url = new URL(request.url);
  const pathname = url.pathname;

  // 1. Check for redirects FIRST (before any SPA fallback)
  const redirectDest = resolveRedirect(pathname);
  if (redirectDest) {
    return Response.redirect(new URL(redirectDest, url.origin).toString(), 301);
  }

  // 2. Check if it's a valid application route
  if (isValidRoute(pathname)) {
    // Pass through to SPA (static asset serving)
    return env.ASSETS.fetch(request);
  }

  // 3. Unknown URL → real 404
  // Serve the branded 404 page but with HTTP 404 status
  const notFoundUrl = new URL("/404.html", url.origin);
  const notFoundResponse = await env.ASSETS.fetch(notFoundUrl);
  return new Response(notFoundResponse.body, {
    status: 404,
    headers: {
      "Content-Type": "text/html; charset=utf-8",
      "X-Robots-Tag": "noindex, follow",
    },
  });
};
